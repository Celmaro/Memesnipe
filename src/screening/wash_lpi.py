"""R4-P1-6: wash-trade / LPI manipulation detector (2507.01963).

The cross-chain manipulation study found 82.8% of high-return (>100%)
tokens show artificial growth; two detectable signatures:

- WASH: the same wallet buys then sells the same mint within a short
  window (self-trade creating fake volume). The paper's strong test: a
  large share of volume from addresses that both bought and sold the same
  token in one day.
- LPI (Liquidity-Pool-Based Price Inflation): small strategic purchases
  trigger dramatic price increases — a manipulation trap, not real demand.
  Detectable as a buy whose quote size is small relative to the observed
  price-implication jump it participates in.

This tracker is pure feed-observation: fed the same per-trade events the
rug heuristics already consume (trader, mint, is_buy, quote_amount). It
keeps bounded per-mint event windows and exposes verdicts:

- ``wash_share(mint)``: STRONG-TEST share of observed volume — fraction
  of window quote volume generated by wallets that BOTH bought AND sold
  the mint within `round_trip_window_s`, summing ALL of those wallets'
  events (not just the first side-crossing trade), matching the paper's
  strong test above (2507.01963).
- ``lpi_flags_recent(mint)``: count of small-quote buys that participated
  in a >= ``min_jump_mult`` price jump within ``lpi_window_s``.

The trader decides how to gate (default: refuse when wash_share is above
``max_wash_share``; LPI counts feed the rug-score feature). No RPC, no
trader dependency.
"""

from __future__ import annotations

from collections import defaultdict, deque


class WashLpiDetector:
    """Bounded wash-trade / LPI tracker over trade-feed observations."""

    def __init__(
        self,
        max_mints: int = 500,
        round_trip_window_s: float = 300.0,
        lpi_window_s: float = 60.0,
        lpi_small_quote_sol: float = 0.05,
        min_jump_mult: float = 3.0,
    ) -> None:
        self.max_mints = max_mints
        self.round_trip_window_s = round_trip_window_s
        self.lpi_window_s = lpi_window_s
        self.lpi_small_quote_sol = lpi_small_quote_sol
        self.min_jump_mult = min_jump_mult
        # mint -> deque[(ts, wallet, is_buy, quote_lamports)]
        self._events: dict[str, deque] = defaultdict(deque)

    def observe_trade(
        self,
        mint: str,
        wallet: str,
        *,
        is_buy: bool,
        quote_lamports: int,
        ts: float,
        token_price: float | None = None,
    ) -> None:
        """Feed one trade event. ``token_price`` is the implied unit price
        if available (used for the LPI jump test; None skips it)."""
        if not mint:
            return
        q = self._events[mint]
        q.append((ts, wallet, is_buy, quote_lamports, token_price))
        cutoff = ts - max(self.round_trip_window_s, self.lpi_window_s)
        while q and q[0][0] < cutoff:
            q.popleft()
        if len(self._events) > self.max_mints:
            # Drop the mint with the fewest events (cheap bound).
            victim = min(self._events, key=lambda k: len(self._events[k]))
            del self._events[victim]

    def wash_share(self, mint: str) -> float:
        """Fraction of quote volume from round-tripping wallets (STRONG test).

        The paper's strong test (module docstring, 2507.01963): a wallet
        is a round-tripper when it appears on BOTH sides for the mint
        within the window (buy AND sell), and the wash share is that
        wallet's volume across ALL of its events (both sides) divided by
        the window's total observed quote volume. Summing every event —
        not just the first opposite-side trade — is what makes this the
        strong test: a wallet that bought 3 SOL and sold 2 SOL injects
        the full 5 SOL of fake volume, not just 2 SOL.

        Round-trippers are identified FIRST over the whole window, then
        their summed quote is divided by total quote. 0.0 = no round-
        trippers or no observations (fail open).
        """
        events = self._events.get(mint)
        if not events:
            return 0.0
        buyers: set[str] = set()
        sellers: set[str] = set()
        for _ts, wallet, is_buy, _q, _px in events:
            if is_buy:
                buyers.add(wallet)
            else:
                sellers.add(wallet)
        round_trippers = buyers & sellers
        if not round_trippers:
            return 0.0
        total_quote = 0.0
        round_trip_quote = 0.0
        for _ts, wallet, _ib, q, _px in events:
            q_sol = (q or 0) / 1e9
            total_quote += q_sol
            if wallet in round_trippers:
                round_trip_quote += q_sol
        return round_trip_quote / total_quote if total_quote > 0 else 0.0

    def lpi_small_buy_count(self, mint: str) -> int:
        """Count of small-quote buys in this mint's window (the raw LPI
        ingredient; the price-jump leg needs token_price observations)."""
        events = self._events.get(mint)
        if not events:
            return 0
        return sum(
            1
            for _ts, _w, is_buy, q, _px in events
            if is_buy and (q or 0) / 1e9 <= self.lpi_small_quote_sol
        )

    def lpi_flags_recent(self, mint: str) -> int:
        """Count of LPI events: a small buy immediately followed by a price
        jump >= min_jump_mult (paper: small purchase -> dramatic jump)."""
        events = list(self._events.get(mint) or [])
        flags = 0
        for i, (_ts, _w, is_buy, q, px) in enumerate(events):
            if not (is_buy and (q or 0) / 1e9 <= self.lpi_small_quote_sol):
                continue
            if px is None:
                continue
            # Look forward for a large price jump within the window.
            for _ts2, _w2, _ib2, _q2, px2 in events[i + 1 :]:
                if px2 is None or px2 <= 0:
                    continue
                if px2 >= px * self.min_jump_mult:
                    flags += 1
                    break
        return flags

    def price_path(self, mint: str) -> list[float]:
        """Observed implied unit prices for the mint (R4-P3-1 VDS input)."""
        events = self._events.get(mint)
        if not events:
            return []
        return [px for (_ts, _w, _ib, _q, px) in events if px is not None and px > 0]

    def event_rate_per_min(self, mint: str) -> float | None:
        """Fills/min over the observed window (R4-P3-1 SAS input)."""
        events = self._events.get(mint)
        if not events:
            return None
        span = events[-1][0] - events[0][0]
        if span <= 0:
            return None
        return len(events) / (span / 60.0)